// Package install generates, installs and removes the tunecord systemd
// user unit.
package install

import (
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"tunecord/internal/config"
	"tunecord/internal/control"
)

// UnitPath returns the path of the user unit file.
func UnitPath() string {
	return filepath.Join(config.SystemdUserDir(), control.UnitName)
}

// ResolveExecutable returns the absolute, symlink-resolved path of the
// running binary.
func ResolveExecutable() (string, error) {
	exe, err := os.Executable()
	if err != nil {
		return "", fmt.Errorf("cannot determine the tunecord binary path: %w", err)
	}
	if resolved, err := filepath.EvalSymlinks(exe); err == nil {
		exe = resolved
	}
	abs, err := filepath.Abs(exe)
	if err != nil {
		return "", fmt.Errorf("cannot make %q absolute: %w", exe, err)
	}
	return abs, nil
}

// quoteExec quotes a path for an ExecStart= line (systemd C-style quoting
// rules), escaping specifiers and quotes.
func quoteExec(p string) string {
	p = strings.ReplaceAll(p, "%", "%%")
	if !strings.ContainsAny(p, " \t\"'\\$;") {
		return p
	}
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range p {
		switch r {
		case '"', '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '$':
			b.WriteString("$$")
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// UnitContent renders the systemd user unit for the given absolute binary path.
func UnitContent(execPath string) (string, error) {
	if !filepath.IsAbs(execPath) {
		return "", fmt.Errorf("ExecStart path must be absolute, got %q", execPath)
	}
	return fmt.Sprintf(`# Generated by 'tunecord install --user'. Re-run it to update this file.
[Unit]
Description=tunecord (MPRIS to Discord Rich Presence)
Documentation=https://github.com/cmerk2021/tunecore
After=graphical-session.target
PartOf=graphical-session.target

[Service]
Type=simple
ExecStart=%s run
Restart=on-failure
RestartSec=5

[Install]
WantedBy=graphical-session.target
`, quoteExec(execPath)), nil
}

// Runner abstracts `systemctl --user` for tests.
type Runner func(ctx context.Context, args ...string) (string, error)

// Options for Install/Uninstall.
type Options struct {
	ExecPath  string // absolute binary path; resolved when empty
	UnitPath  string // defaults to UnitPath()
	Systemctl Runner
	Out       io.Writer
}

func (o *Options) defaults() error {
	if o.UnitPath == "" {
		o.UnitPath = UnitPath()
	}
	if o.Systemctl == nil {
		if !control.HaveSystemctl() {
			return errors.New("systemctl not found: tunecord install requires systemd. Run 'tunecord run' from your session autostart instead")
		}
		o.Systemctl = control.Systemctl
	}
	if o.Out == nil {
		o.Out = io.Discard
	}
	return nil
}

// Install writes (or updates) the unit, reloads systemd and enables+starts it.
func Install(ctx context.Context, o Options) error {
	if err := o.defaults(); err != nil {
		return err
	}
	if o.ExecPath == "" {
		p, err := ResolveExecutable()
		if err != nil {
			return err
		}
		o.ExecPath = p
	}
	content, err := UnitContent(o.ExecPath)
	if err != nil {
		return err
	}
	old, _ := os.ReadFile(o.UnitPath)
	changed := string(old) != content
	if changed {
		if err := os.MkdirAll(filepath.Dir(o.UnitPath), 0o755); err != nil {
			return fmt.Errorf("create %s: %w", filepath.Dir(o.UnitPath), err)
		}
		if err := config.WriteFileAtomic(o.UnitPath, []byte(content), 0o644); err != nil {
			return fmt.Errorf("write unit: %w", err)
		}
		if len(old) == 0 {
			fmt.Fprintf(o.Out, "Wrote %s\n", o.UnitPath)
		} else {
			fmt.Fprintf(o.Out, "Updated %s\n", o.UnitPath)
		}
	} else {
		fmt.Fprintf(o.Out, "%s is up to date\n", o.UnitPath)
	}
	fmt.Fprintf(o.Out, "ExecStart=%s run\n", o.ExecPath)
	if _, err := o.Systemctl(ctx, "daemon-reload"); err != nil {
		return err
	}
	if _, err := o.Systemctl(ctx, "enable", "--now", control.UnitName); err != nil {
		return err
	}
	if changed && len(old) > 0 {
		// A running instance may still use the old binary path.
		if _, err := o.Systemctl(ctx, "restart", control.UnitName); err != nil {
			return err
		}
	}
	fmt.Fprintf(o.Out, "Enabled and started %s\n", control.UnitName)
	return nil
}

// Uninstall stops, disables and removes the unit. Missing pieces are not errors.
func Uninstall(ctx context.Context, o Options) error {
	if err := o.defaults(); err != nil {
		return err
	}
	if _, err := o.Systemctl(ctx, "disable", "--now", control.UnitName); err != nil {
		fmt.Fprintf(o.Out, "Note: %v\n", err)
	} else {
		fmt.Fprintf(o.Out, "Stopped and disabled %s\n", control.UnitName)
	}
	switch err := os.Remove(o.UnitPath); {
	case err == nil:
		fmt.Fprintf(o.Out, "Removed %s\n", o.UnitPath)
	case errors.Is(err, os.ErrNotExist):
		fmt.Fprintf(o.Out, "%s was not installed\n", o.UnitPath)
	default:
		return fmt.Errorf("remove unit: %w", err)
	}
	if _, err := o.Systemctl(ctx, "daemon-reload"); err != nil {
		return err
	}
	_, _ = o.Systemctl(ctx, "reset-failed", control.UnitName)
	return nil
}

// LocalBin returns ~/.local/bin.
func LocalBin() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return filepath.Join(home, ".local", "bin")
}

// InPath reports whether dir is an entry of the PATH-style list pathEnv.
func InPath(dir, pathEnv string) bool {
	if dir == "" {
		return false
	}
	clean := filepath.Clean(dir)
	for _, p := range filepath.SplitList(pathEnv) {
		if p != "" && filepath.Clean(p) == clean {
			return true
		}
	}
	return false
}

// PathHint returns a warning (with the line to add to the shell config)
// when ~/.local/bin is not on PATH, or "" if it is.
func PathHint(pathEnv string) string {
	lb := LocalBin()
	if lb == "" || InPath(lb, pathEnv) {
		return ""
	}
	return fmt.Sprintf("Warning: %s is not in your $PATH, so typing 'tunecord' may not work in a shell.\n"+
		"Add this line to ~/.bashrc, ~/.zshrc or ~/.profile (fish: fish_add_path ~/.local/bin):\n\n"+
		"    export PATH=\"$HOME/.local/bin:$PATH\"\n\n"+
		"(The service itself is unaffected: the unit uses the absolute binary path.)", lb)
}
